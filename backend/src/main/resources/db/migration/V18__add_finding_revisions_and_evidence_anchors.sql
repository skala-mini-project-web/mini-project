CREATE FUNCTION validate_finding_evidence_anchor()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM findings
        WHERE id = NEW.finding_id
          AND analysis_execution_id IS NOT NULL
          AND lineage_id IS NOT NULL
          AND revision_number IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'evidence anchors require an execution-bound finding revision'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_finding_evidence_anchors_validate
BEFORE INSERT ON finding_evidence_anchors
FOR EACH ROW
EXECUTE FUNCTION validate_finding_evidence_anchor();

