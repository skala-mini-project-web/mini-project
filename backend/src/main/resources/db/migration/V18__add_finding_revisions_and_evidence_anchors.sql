CREATE TABLE finding_evidence_anchors (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id           BIGINT       NOT NULL REFERENCES findings (id),
    source_role          VARCHAR(30)  NOT NULL,
    source_document_id   BIGINT,
    source_revision_id   BIGINT,
    evidence_document_id BIGINT,
    retrieved_chunk_id   BIGINT,
    source_hash          VARCHAR(64)  NOT NULL,
    page_number          INTEGER      NOT NULL,
    utf8_start_offset    BIGINT       NOT NULL,
    utf8_end_offset      BIGINT       NOT NULL,
    excerpt_hash         VARCHAR(64)  NOT NULL,
    exact_excerpt        TEXT         NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_finding_evidence_anchors_document_source
        FOREIGN KEY (source_revision_id, source_document_id, source_hash)
        REFERENCES document_source_revisions (id, product_document_id, source_hash),
    CONSTRAINT fk_finding_evidence_anchors_policy_source
        FOREIGN KEY (retrieved_chunk_id, evidence_document_id, source_hash)
        REFERENCES evidence_document_chunks (id, evidence_document_id, source_hash),
    CONSTRAINT ck_finding_evidence_anchors_role
        CHECK (source_role IN ('DOCUMENT_CLAIM', 'POLICY_REQUIREMENT')),
    CONSTRAINT ck_finding_evidence_anchors_source_identity CHECK (
        (source_role = 'DOCUMENT_CLAIM'
            AND source_document_id IS NOT NULL
            AND source_revision_id IS NOT NULL
            AND evidence_document_id IS NULL
            AND retrieved_chunk_id IS NULL)
        OR
        (source_role = 'POLICY_REQUIREMENT'
            AND source_document_id IS NULL
            AND source_revision_id IS NULL
            AND evidence_document_id IS NOT NULL
            AND retrieved_chunk_id IS NOT NULL)
    ),
    CONSTRAINT ck_finding_evidence_anchors_source_hash
        CHECK (source_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_finding_evidence_anchors_page
        CHECK (page_number > 0),
    CONSTRAINT ck_finding_evidence_anchors_utf8_range
        CHECK (utf8_start_offset >= 0 AND utf8_end_offset > utf8_start_offset),
    CONSTRAINT ck_finding_evidence_anchors_excerpt_hash
        CHECK (excerpt_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_finding_evidence_anchors_excerpt
        CHECK (octet_length(exact_excerpt) = utf8_end_offset - utf8_start_offset)
);

